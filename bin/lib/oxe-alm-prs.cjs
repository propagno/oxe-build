'use strict';

/**
 * OxeSpace 15/11 (coordinator, OXE-277): cards went to "Na main" on the first PR citing their key, even when the PR
 * was only part of the card (4 of 51 wrong). `oxe-cc alm pr-merged --pr N [--apply]` reads the markers of a merged
 * PR — "Fecha/Closes KEY" moves the card to integrated, "Parte de/Part of KEY" only comments the PR link, a bare key
 * is reported and not moved — and `oxe-cc alm list --state "<name>"[,…] [--with-prs]` lists the cards in those board
 * states with the merged PRs that cite each one. Every write goes through oxe-cc alm (the repo workflow calls it).
 */

const fs = require('fs');
const path = require('path');
const { spawnSync } = require('child_process');

const CLOSE_WORDS = '(?:Fecha|Fechas|Fechar|Closes|Close|Closed|Fixes|Fix|Resolves|Resolve)';
const PART_WORDS = '(?:Parte[\\s-]+de|Part[\\s-]+of|Refs?|Relacionad[oa]\\s+a)';

/** The key regex of the configured provider (Jira PROJ-n; Azure AB#n). */
function keyPattern(cfg) {
  if (cfg && cfg.provider === 'azure-devops') return 'AB#\\d+';
  const proj = cfg && cfg.p && cfg.p.project ? String(cfg.p.project).toUpperCase().replace(/[^A-Z0-9]/g, '') : '[A-Z][A-Z0-9]+';
  return `${proj}-\\d+`;
}

const normKey = (k) => String(k).toUpperCase().replace(/^AB#/, 'AB#');

/**
 * The markers of a PR text (title, body, commit messages and trailers). A key both closed and partial counts as closed.
 * @returns {{ closes: string[], partial: string[], bare: string[] }}
 */
function prMarkers(texts, cfg) {
  const kp = keyPattern(cfg);
  // a list of keys: "A, B e C", "A, B, and C" (Oxford comma), "A/B", "A & B" (R42)
  const sep = '(?:\\s*,\\s*(?:e|and|&)\\s+|\\s*[,/&]\\s*|\\s+(?:e|and)\\s+)';
  const list = `(${kp}(?:${sep}${kp})*)`;
  const all = (Array.isArray(texts) ? texts : [texts]).map((t) => String(t || '')).join('\n');
  const closes = new Set();
  const partial = new Set();
  // R42: a marker is a DIRECTIVE — at the start of a line (or after "-", "*", "(", ".", ";", ":"), or with a colon
  // ("Fecha: X"). Prose ("quando o modal fecha OXE-105") and a negation ("não fecha", "does not close") never count.
  const lead = '(?:^|[\\r\\n]|[-*(.;:]\\s*)\\s*';
  const neg = '(?<!\\b(?:n[ãa]o|sem|nunca|not|never|doesn\'t|don\'t|won\'t|isn\'t)\\s+)';
  const grab = (words, into) => {
    const res = [new RegExp(`${lead}${neg}${words}\\s*:?\\s+${list}`, 'gim'), new RegExp(`${neg}\\b${words}\\s*:\\s*${list}`, 'gi')];
    for (const re of res) for (const m of all.matchAll(re)) for (const k of m[1].match(new RegExp(kp, 'gi')) || []) into.add(normKey(k));
  };
  grab(CLOSE_WORDS, closes);
  grab(PART_WORDS, partial);
  // 1.23.0 (OXB-G11): `OXE-Part-Of: KEY (k/N)` (or `OXE-Part-Of: KEY`) marks a multi-PR card part explicitly.
  // Cards with `OXE-Part-Of` stay partial until ALL 1..N parts land on main (even if `OXE-Card: KEY` is also present).
  const parts = [];
  const partKeySet = new Set();
  const partRe = new RegExp(`(?:^|[\\r\\n])\\s*OXE-Part-Of\\s*:\\s*(${kp})(?:\\s*\\(\\s*(\\d+)\\s*\\/\\s*(\\d+)\\s*\\))?`, 'gim');
  for (const m of all.matchAll(partRe)) {
    const k = normKey(m[1]);
    const part = m[2] ? Number(m[2]) : null;
    const total = m[3] ? Number(m[3]) : null;
    partKeySet.add(k);
    partial.add(k);
    parts.push({ key: k, part, total });
  }
  // OXB-C18 (#2): `OXE-Card: <KEY>` trailer (generated by `oxe-cc quick commit`) closes the card unless explicitly marked partial.
  for (const m of all.matchAll(new RegExp(`(?:^|[\\r\\n])\\s*OXE-Card\\s*:\\s*(${kp})\\b`, 'gim'))) {
    const k = normKey(m[1]);
    if (!partial.has(k) && !partKeySet.has(k)) closes.add(k);
  }
  for (const k of closes) partial.delete(k);
  const bare = new Set();
  for (const k of all.match(new RegExp(kp, 'gi')) || []) { const n = normKey(k); if (!closes.has(n) && !partial.has(n)) bare.add(n); }
  return { closes: [...closes].sort(), partial: [...partial].sort(), bare: [...bare].sort(), parts };
}

function gh(args, cwd, spawn) {
  const r = (spawn || spawnSync)('gh', args, { cwd, encoding: 'utf8', windowsHide: true, timeout: 60_000, maxBuffer: 32 * 1024 * 1024 });
  if (!r || r.status !== 0) throw new Error(`gh ${args.slice(0, 3).join(' ')} falhou: ${String((r && (r.stderr || r.error)) || 'sem saída').trim().split(/\r?\n/).slice(-2).join(' · ')}`);
  return JSON.parse(String(r.stdout || 'null'));
}

/** A PR with its text parts: title, branch, body and each commit's message (gh pr view). */
function readPr(root, pr, options = {}) {
  const n = String(pr || '').replace(/^#/, '');
  if (!/^\d+$/.test(n)) throw new Error('informe o número do PR (--pr 771)');
  const args = ['pr', 'view', n, '--json', 'number,title,body,headRefName,url,state,mergedAt,commits'];
  if (options.repo) args.push('-R', options.repo);
  const j = gh(args, root, options.ghSpawn);
  const commits = (j.commits || []).map((c) => [c.messageHeadline, c.messageBody].filter(Boolean).join('\n'));
  return { number: j.number, title: j.title || '', branch: j.headRefName || '', body: j.body || '', url: j.url || null, state: String(j.state || '').toUpperCase(), merged_at: j.mergedAt || null, commits };
}

const ledgerFile = (programDir) => path.join(programDir, 'alm-pr-merged.ndjson');
function ledger(programDir) {
  try { return fs.readFileSync(ledgerFile(programDir), 'utf8').split(/\r?\n/).filter(Boolean).map((l) => { try { return JSON.parse(l); } catch { return null; } }).filter(Boolean); } catch { return []; }
}

/**
 * `alm pr-merged --pr N`: dry run by default (the plan); with apply, the closed keys move to integrated once (a key
 * already moved by this PR is skipped), the partial ones get a comment with the PR link. Bare keys are only reported.
 */
async function prMerged(root, programDir, cfg, almLib, options = {}) {
  const pr = options.prData || readPr(root, options.pr, options);
  if (pr.state !== 'MERGED') throw new Error(`PR #${pr.number} não está mergeado (${pr.state || 'estado desconhecido'}) — nada a mover`);
  const m = prMarkers([pr.title, pr.branch, pr.body, ...pr.commits], cfg);
  // OXB-C18 (#2): if a PR has no explicit Fecha/Parte de markers, a single bare key present in the title AND already
  // linked in the ALM ledger (`alm link`) counts as a valid close target.
  if (m.bare.length === 1 && m.closes.length === 0 && m.partial.length === 0) {
    const candidate = m.bare[0];
    const titleKeys = new Set((String(pr.title || '').match(new RegExp(keyPattern(cfg), 'gi')) || []).map(normKey));
    if (titleKeys.has(candidate)) {
      let linked = false;
      try {
        const linksMap = almLib && typeof almLib.links === 'function' ? almLib.links(programDir) : null;
        if (linksMap && typeof linksMap.values === 'function') {
          for (const rec of linksMap.values()) {
            if (rec && normKey(rec.key || '') === candidate) { linked = true; break; }
          }
        }
      } catch { linked = false; }
      if (linked) {
        m.closes.push(candidate);
        m.bare = [];
      }
    }
  }
  const allLedger = ledger(programDir);
  const done = new Set(allLedger.filter((r) => r.pr === pr.number).map((r) => `${r.action}:${r.key}`));
  // OXB-G11: Track multi-PR parts (`OXE-Part-Of: KEY (k/N)`). Promote card to `close` automatically once ALL 1..N parts landed!
  const partMap = new Map();
  for (const p of m.parts || []) {
    if (!partMap.has(p.key)) partMap.set(p.key, []);
    partMap.get(p.key).push(p);
  }
  const partProgress = [];
  for (const [key, entries] of partMap.entries()) {
    const priorParts = new Set(allLedger.filter((r) => r.action === 'part' && r.key === key && Number.isInteger(r.part)).map((r) => r.part));
    let total = null;
    for (const e of entries) {
      if (Number.isInteger(e.part)) priorParts.add(e.part);
      if (Number.isInteger(e.total) && e.total > 0) total = Math.max(total || 0, e.total);
    }
    if (!total) {
      const priorTotal = allLedger.find((r) => r.action === 'part' && r.key === key && Number.isInteger(r.total));
      if (priorTotal) total = priorTotal.total;
    }
    const complete = Boolean(total && priorParts.size >= total && Array.from({ length: total }, (_, i) => i + 1).every((n) => priorParts.has(n)));
    partProgress.push({ key, received: [...priorParts].sort((a, b) => a - b), total, complete });
    if (complete && !m.closes.includes(key)) {
      m.closes.push(key);
      m.partial = m.partial.filter((k) => k !== key);
    }
  }
  const plan = {
    pr: pr.number,
    url: pr.url,
    close: m.closes.map((key) => ({ key, stage: 'integrated', skip: done.has(`moved:${key}`) })),
    comment: m.partial.map((key) => ({ key, skip: done.has(`commented:${key}`) })),
    bare: m.bare,
    ...(partProgress.length ? { parts: partProgress } : {}),
  };
  if (!options.apply) return { dry_run: true, ...plan };
  const out = { ...plan, moved: [], commented: [], errors: [] };
  const net = { ...(options.net || {}), dryRun: false };
  const at = new Date().toISOString();
  const rec = (r) => { fs.mkdirSync(programDir, { recursive: true }); fs.appendFileSync(ledgerFile(programDir), `${JSON.stringify({ ...r, pr: pr.number, at })}\n`, 'utf8'); };
  // Record newly landed parts in the ledger before closing/commenting
  for (const p of m.parts || []) {
    if (Number.isInteger(p.part) && !allLedger.some((r) => r.action === 'part' && r.key === p.key && r.part === p.part)) {
      rec({ action: 'part', key: p.key, part: p.part, total: p.total || null });
    }
  }
  for (const c of plan.close) {
    if (c.skip) continue;
    try {
      // R43: without the integrated state mapped nothing can move — an error, never recorded as done
      if (!cfg.states || !cfg.states.integrated) { out.errors.push(`${c.key}: alm.states.integrated não está mapeado no .oxe/config.json — nada movido`); continue; }
      // only forward (R42): a card already at/after integrated is never moved back; an unmapped live state
      // ("Backlog", "Em revisão") is before it and moves (R43)
      const atStage = await almLib.stageAtOrPast(programDir, cfg, c.key, 'integrated', net);
      if (atStage.past) {
        out.moved.push({ key: c.key, already: true, why: `o card já está em "${atStage.live}" (${atStage.liveStage})` });
        rec({ action: 'moved', key: c.key });
        continue;
      }
      const pp = partProgress.find((x) => x.key === c.key && x.complete);
      const commentTxt = pp
        ? `PR #${pr.number} mergeado (${pr.url || ''}) — todas as partes (${pp.received.length}/${pp.total}) na main; fechando o card`
        : `PR #${pr.number} mergeado (${pr.url || ''}) — fecha o card`;
      const r = await almLib.move(programDir, cfg, c.key, 'integrated', { ...net, comment: commentTxt });
      if (r && r.planned) continue; // cfg.dry_run: nothing was written, nothing recorded
      out.moved.push({ key: c.key, ...(r && r.queued ? { queued: true } : {}), ...(r && r.changed === false ? { already: true } : {}) });
      rec({ action: 'moved', key: c.key });
    } catch (err) { out.errors.push(`${c.key}: ${err.message}`); }
  }
  for (const c of plan.comment) {
    if (c.skip) continue;
    try {
      const pp = partProgress.find((x) => x.key === c.key);
      const partNote = pp && pp.total
        ? `parte(s) ${pp.received.join(', ')}/${pp.total} na main — aguardando partes restantes`
        : 'parte deste card; o card segue aberto até o PR que o fecha';
      await almLib.comment(programDir, cfg, c.key, `PR #${pr.number} mergeado (${pr.url || ''}) — ${partNote}`, net);
      out.commented.push(c.key);
      rec({ action: 'commented', key: c.key });
    } catch (err) { out.errors.push(`${c.key}: ${err.message}`); }
  }
  return out;
}

/**
 * The merged PRs that cite each key (gh pr list --state merged), with the kind of citation.
 * @returns {Map<string, { pr: number, url: string|null, kind: 'closes'|'partial'|'bare', merged_at: string|null }[]>}
 */
function mergedPrsByKey(root, cfg, options = {}) {
  const args = ['pr', 'list', '--state', 'merged', '--limit', String(options.limit || 500), '--json', 'number,title,body,headRefName,url,mergedAt'];
  if (options.repo) args.push('-R', options.repo);
  const prs = gh(args, root, options.ghSpawn) || [];
  const out = new Map();
  for (const p of prs) {
    const m = prMarkers([p.title, p.headRefName, p.body], cfg);
    const add = (k, kind) => { if (!out.has(k)) out.set(k, []); out.get(k).push({ pr: p.number, url: p.url || null, kind, merged_at: p.mergedAt || null }); };
    for (const k of m.closes) add(k, 'closes');
    for (const k of m.partial) add(k, 'partial');
    for (const k of m.bare) add(k, 'bare');
  }
  return out;
}

/** "Parte de KEY" or "Fecha KEY" for a task PR: Fecha only when no other open task of the plan shares the card. */
function prMarkerFor(key, taskId, planDoc, keyOfTask) {
  if (!key) return null;
  const others = ((planDoc && planDoc.tasks) || []).filter((t) => t && t.id !== taskId && !(t.done === true || t.status === 'done') && !t.superseded && !t.merged_into && keyOfTask(t.id) === key);
  return others.length ? { marker: `Parte de ${key}`, open_tasks: others.map((t) => t.id) } : { marker: `Fecha ${key}`, open_tasks: [] };
}

/**
 * 1.23.0 (OXB-G11): Evaluates whether a parent Epic is ready to close because 100% of its child issues
 * have reached an approved/homologated/done state.
 */
function checkEpicClosure(epicKey, children, options = {}) {
  const doneStates = new Set((options.doneStates || ['homologado', 'lançado', 'lancado', 'done', 'concluído', 'concluido', 'released']).map((s) => String(s).toLowerCase()));
  const list = Array.isArray(children) ? children : [];
  const open = list.filter((c) => !doneStates.has(String((c && c.status) || '').toLowerCase()));
  const doneCount = list.length - open.length;
  return {
    epic: normKey(epicKey),
    total_children: list.length,
    done_children: doneCount,
    open_children: open.map((c) => ({ key: c.key, status: c.status })),
    ready_to_close: list.length > 0 && open.length === 0,
  };
}

/**
 * Queries or uses injected children of `epicKey`, and when 100% are homologated/done, suggests or executes Epic closure.
 */
async function syncEpicClosure(programDir, cfg, almLib, epicKey, options = {}) {
  let children = Array.isArray(options.children) ? options.children : null;
  if (!children && typeof options.fetchChildren === 'function') {
    children = await options.fetchChildren(epicKey);
  }
  if (!children) children = [];
  const check = checkEpicClosure(epicKey, children, options);
  if (!check.ready_to_close || !options.apply) {
    return { ...check, dry_run: !options.apply, closed: false };
  }
  const targetStage = options.stage || 'released';
  await almLib.move(programDir, cfg, check.epic, targetStage, {
    ...(options.net || {}),
    dryRun: false,
    comment: `100% dos filhos (${check.done_children}/${check.total_children}) homologados/concluídos — fechando épico ${check.epic}.`,
  });
  return { ...check, dry_run: false, closed: true };
}

module.exports = { prMarkers, readPr, prMerged, mergedPrsByKey, prMarkerFor, checkEpicClosure, syncEpicClosure, keyPattern, ledger };
